#!/usr/bin/env python3
"""SLO-as-code generator.

Reads slos/slos.yaml and writes three files:

  stack/compose/prometheus/rules/slo-recording.rules.yml  SLI + error-budget recording rules
  stack/compose/prometheus/rules/slo-alerts.rules.yml     multi-window, multi-burn-rate alerts
  tests/slo-alerts.test.yml                               promtool unit tests for those alerts

Usage (works from any folder):
  python tools/slo_generator.py           write / refresh the files
  python tools/slo_generator.py --check   only check that the files are up to date (used by CI)

Alerting policy (Google SRE Workbook, chapter 5 "Alerting on SLOs"):
  page   : 2% of the budget burnt in 1h (burn rate 14.4, confirmed by the 5m window)
           or 5% burnt in 6h (burn rate 6, confirmed by the 30m window)
  ticket : 10% burnt in 1d (burn rate 3, confirmed by the 2h window)
           or 10% burnt in 3d (burn rate 1, confirmed by the 6h window)
"""

from __future__ import annotations

import argparse
import re
import sys
from decimal import Decimal, InvalidOperation
from pathlib import Path

try:
    import yaml
except ImportError:
    sys.exit("PyYAML is not installed. Run:  python -m pip install -r tools/requirements.txt")

ROOT = Path(__file__).resolve().parent.parent
SPEC_FILE = ROOT / "slos" / "slos.yaml"
RULES_DIR = ROOT / "stack" / "compose" / "prometheus" / "rules"
RECORDING_FILE = RULES_DIR / "slo-recording.rules.yml"
ALERTS_FILE = RULES_DIR / "slo-alerts.rules.yml"
TESTS_FILE = ROOT / "tests" / "slo-alerts.test.yml"

HEADER = "# GENERATED by tools/slo_generator.py from slos/slos.yaml - do not edit by hand.\n"

WINDOW = "{{window}}"
SLI_WINDOWS = ["5m", "30m", "1h", "2h", "6h", "1d", "3d"]
SLI_EVAL_SECONDS = 30  # evaluation interval of the SLI recording-rule groups
PERIOD_DAYS = {"28d": 28, "30d": 30}
FAST, SLOW = "ErrorBudgetBurnFast", "ErrorBudgetBurnSlow"

# (severity, alert name, [(long window, short window, burn-rate factor), ...])
POLICY = [
    ("page", FAST, [("1h", "5m", Decimal("14.4")), ("6h", "30m", Decimal("6"))]),
    ("ticket", SLOW, [("1d", "2h", Decimal("3")), ("3d", "6h", Decimal("1"))]),
]

ALLOWED_KEYS = {"name", "service", "description", "objective", "period", "sli",
                "runbook_base_url", "dashboard_url"}
SLO_NAME = re.compile(r"^[a-z0-9]([a-z0-9-]{0,38}[a-z0-9])?$")
LABEL_VALUE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,62}$")


class SpecError(Exception):
    """A problem in slos.yaml, explained in plain words."""


def num(value: Decimal) -> str:
    """Shortest plain-number text: Decimal('0.0050') -> '0.005', Decimal('216.0') -> '216'."""
    return format(value.normalize(), "f")


def load_spec(path: Path) -> list[dict]:
    try:
        data = yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, yaml.YAMLError) as exc:
        raise SpecError(f"cannot read the file:\n{exc}") from exc
    if not isinstance(data, dict) or not isinstance(data.get("slos"), list) or not data["slos"]:
        raise SpecError("the file must contain a non-empty 'slos:' list")
    defaults = data.get("defaults") or {}
    if not isinstance(defaults, dict):
        raise SpecError("'defaults' must be a mapping")

    slos, seen = [], set()
    for index, entry in enumerate(data["slos"], start=1):
        if not isinstance(entry, dict):
            raise SpecError(f"entry #{index} under 'slos' must be a mapping")
        spec = {**defaults, **entry}
        name = str(spec.get("name", ""))
        where = f"SLO '{name}'" if name else f"SLO #{index}"

        unknown = set(spec) - ALLOWED_KEYS
        if unknown:
            raise SpecError(f"{where}: unknown key(s) {sorted(unknown)} (typo?)")
        if not SLO_NAME.match(name):
            raise SpecError(f"{where}: 'name' must be 1-40 characters of a-z, 0-9 and '-'")
        if name in seen:
            raise SpecError(f"{where}: the name is used twice")
        seen.add(name)

        service = str(spec.get("service", ""))
        if not LABEL_VALUE.match(service):
            raise SpecError(f"{where}: 'service' must be letters, digits, '.', '_' or '-'")

        try:
            objective = Decimal(str(spec.get("objective")))
        except InvalidOperation:
            raise SpecError(f"{where}: 'objective' must be a number such as 99.5") from None
        if not Decimal("90") <= objective <= Decimal("99.99"):
            raise SpecError(f"{where}: 'objective' must be between 90 and 99.99 (it is a percentage)")

        period = str(spec.get("period", "30d"))
        if period not in PERIOD_DAYS:
            raise SpecError(f"{where}: 'period' must be one of {sorted(PERIOD_DAYS)}")

        urls = {}
        for key in ("runbook_base_url", "dashboard_url"):
            url = spec.get(key)
            if not isinstance(url, str) or not url.startswith(("https://", "http://")):
                raise SpecError(f"{where}: '{key}' must be a URL starting with http:// or https://")
            urls[key] = url.rstrip("/")

        sli = spec.get("sli")
        if not isinstance(sli, dict) or len(sli) != 1 or next(iter(sli)) not in ("events", "raw"):
            raise SpecError(f"{where}: 'sli' must contain exactly one of 'events' or 'raw'")
        kind = next(iter(sli))
        fields = ("error_query", "total_query") if kind == "events" else ("error_ratio_query",)
        body = sli[kind]
        if not isinstance(body, dict) or set(body) != set(fields):
            raise SpecError(f"{where}: 'sli.{kind}' must contain exactly: {', '.join(fields)}")
        queries = {}
        for field in fields:
            query = body[field]
            if not isinstance(query, str) or WINDOW not in query:
                raise SpecError(f"{where}: sli.{kind}.{field} must be PromQL text containing {WINDOW}")
            queries[field] = " ".join(line.strip() for line in query.strip().splitlines())

        slos.append({
            "name": name,
            "service": service,
            "objective": objective,
            "budget": (Decimal(100) - objective) / Decimal(100),
            "period": period,
            "days": PERIOD_DAYS[period],
            "kind": kind,
            "queries": queries,
            "runbook_url": f"{urls['runbook_base_url']}/{name}.md",
            "dashboard_url": f"{urls['dashboard_url']}?var-slo={name}",
        })
    return slos


def sli_error_expr(slo: dict, window: str) -> str:
    """PromQL for the SLI error ratio (0..1) over one window."""
    q = {key: text.replace(WINDOW, window) for key, text in slo["queries"].items()}
    if slo["kind"] == "raw":
        return q["error_ratio_query"]
    # "or vector(0)": no error series yet means 0 errors, not "no data".
    # "> 0": no traffic at all gives "no data" instead of 0/0 = NaN, which would poison the budget maths.
    return ("(\n"
            f"  ({q['error_query']})\n"
            "  or vector(0)\n"
            ")\n"
            "/\n"
            "(\n"
            f"  ({q['total_query']}) > 0\n"
            ")")


def recording_groups(slo: dict) -> list[dict]:
    sel = f'{{slo="{slo["name"]}"}}'
    labels = {"slo": slo["name"], "service": slo["service"]}
    period = slo["period"]
    budget_minutes = slo["budget"] * slo["days"] * 24 * 60
    minutes_per_sample = Decimal(SLI_EVAL_SECONDS) / Decimal(60)

    sli_rules = [{"record": f"slo:sli_error:ratio_rate{window}",
                  "expr": sli_error_expr(slo, window),
                  "labels": dict(labels)} for window in SLI_WINDOWS]
    budget_rules = [
        {"record": "slo:objective:ratio",
         "expr": f"vector({num(slo['objective'] / 100)})"},
        {"record": "slo:error_budget:ratio",
         "expr": f"vector({num(slo['budget'])})"},
        # The budget expressed as "bad minutes" allowed per period (100% errors for 1 minute = 1 bad minute).
        {"record": "slo:error_budget:minutes",
         "expr": f"vector({num(budget_minutes)})"},
        # Average error ratio over the period (or since the stack started, if that is shorter).
        {"record": "slo:sli_error:ratio_period",
         "expr": f"avg_over_time(slo:sli_error:ratio_rate5m{sel}[{period}])"},
        # Bad minutes used so far: add up the 5m error ratio, one sample every {SLI_EVAL_SECONDS}s.
        {"record": "slo:error_budget_consumed:minutes",
         "expr": f"sum_over_time(slo:sli_error:ratio_rate5m{sel}[{period}]) * {num(minutes_per_sample)}"},
        {"record": "slo:error_budget_remaining:ratio",
         "expr": (f"1 - slo:error_budget_consumed:minutes{sel}"
                  f" / on(slo, service) slo:error_budget:minutes{sel}")},
    ]
    for rule in budget_rules:
        rule["labels"] = dict(labels)
    return [
        {"name": f"slo-sli-{slo['name']}", "interval": f"{SLI_EVAL_SECONDS}s", "rules": sli_rules},
        {"name": f"slo-budget-{slo['name']}", "interval": "1m", "rules": budget_rules},
    ]


def lasts(days: int, factor: Decimal) -> str:
    """How long the whole budget lasts at a given burn rate, in words."""
    total = Decimal(days) / factor
    if total < 3:
        return f"{int((total * 24).to_integral_value())} hours"
    return f"{int(total.to_integral_value())} days"


def annotations(slo: dict, severity: str, windows: list) -> dict:
    speeds = " or ".join(
        f"{num(factor)}x over {long_w} (whole budget gone in ~{lasts(slo['days'], factor)})"
        for long_w, _short_w, factor in windows)
    pace = "fast" if severity == "page" else "slowly"
    return {
        "summary": f"{slo['name']}: error budget is burning {pace}",
        "description": (f"{slo['service']} is burning the {slo['period']} error budget of SLO "
                        f"{slo['name']} ({num(slo['objective'])}%) at {speeds}. "
                        "Long-window error ratio: {{ $value | humanizePercentage }}."),
        "runbook_url": slo["runbook_url"],
        "dashboard_url": slo["dashboard_url"],
    }


def alert_group(slo: dict) -> dict:
    sel = f'{{slo="{slo["name"]}"}}'
    rules = []
    for severity, alertname, windows in POLICY:
        branches = []
        for long_w, short_w, factor in windows:
            threshold = f"({num(factor)} * {num(slo['budget'])})"
            branches.append("(\n"
                            f"  slo:sli_error:ratio_rate{long_w}{sel} > {threshold}\n"
                            "  and\n"
                            f"  slo:sli_error:ratio_rate{short_w}{sel} > {threshold}\n"
                            ")")
        rules.append({
            "alert": alertname,
            "expr": "\nor\n".join(branches),
            "labels": {"severity": severity, "slo": slo["name"], "service": slo["service"]},
            "annotations": annotations(slo, severity, windows),
        })
    return {"name": f"slo-alerts-{slo['name']}", "interval": "30s", "rules": rules}


def humanize_percentage(value: Decimal) -> str:
    """Same text as Prometheus' humanizePercentage template function (Go's %.4g)."""
    return format(float(value) * 100, ".4g") + "%"


def alert_tests(slo: dict) -> list[dict]:
    """promtool unit tests that feed fake SLI values and check which alerts fire."""
    series = f'{{service="{slo["service"]}", slo="{slo["name"]}"}}'
    budget = slo["budget"]
    fast = min(Decimal(1), 20 * budget)  # burn rate 20: must page
    slow = 2 * budget                    # burn rate 2: ticket only

    def inputs(values: dict) -> list[dict]:
        # 41 samples, one every 30s = 20 minutes of data
        return [{"series": f"slo:sli_error:ratio_rate{window}{series}", "values": f"{num(values[window])}x40"}
                for window in SLI_WINDOWS]

    def expected(severity: str, value: Decimal) -> list[dict]:
        windows = next(w for s, _a, w in POLICY if s == severity)
        notes = annotations(slo, severity, windows)
        notes["description"] = notes["description"].replace(
            "{{ $value | humanizePercentage }}", humanize_percentage(value))
        return [{"exp_labels": {"severity": severity, "slo": slo["name"], "service": slo["service"]},
                 "exp_annotations": notes}]

    def case(title: str, values: dict, fast_alerts: list, slow_alerts: list) -> dict:
        return {
            "name": f"{slo['name']}: {title}",
            "interval": "30s",
            "input_series": inputs(values),
            "alert_rule_test": [
                {"eval_time": "15m", "alertname": FAST, "exp_alerts": fast_alerts},
                {"eval_time": "15m", "alertname": SLOW, "exp_alerts": slow_alerts},
            ],
        }

    zero = Decimal(0)
    spike = {w: (Decimal(1) if w in ("5m", "30m") else zero) for w in SLI_WINDOWS}
    return [
        case("healthy service raises no alerts", {w: zero for w in SLI_WINDOWS}, [], []),
        case("fast burn pages (and also opens a ticket)", {w: fast for w in SLI_WINDOWS},
             expected("page", fast), expected("ticket", fast)),
        case("slow burn opens a ticket but does not page", {w: slow for w in SLI_WINDOWS},
             [], expected("ticket", slow)),
        case("short spike does not alert (multi-window at work)", spike, [], []),
    ]


class Dumper(yaml.SafeDumper):
    """YAML writer: indented lists, multi-line strings as '|' blocks."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def _represent_str(dumper: yaml.SafeDumper, value: str):
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


Dumper.add_representer(str, _represent_str)


def render(document: dict) -> str:
    return HEADER + yaml.dump(document, Dumper=Dumper, sort_keys=False, width=1000,
                              allow_unicode=True, default_flow_style=False)


def build(slos: list[dict]) -> dict[Path, str]:
    return {
        RECORDING_FILE: render({"groups": [g for slo in slos for g in recording_groups(slo)]}),
        ALERTS_FILE: render({"groups": [alert_group(slo) for slo in slos]}),
        TESTS_FILE: render({
            "rule_files": ["../stack/compose/prometheus/rules/slo-alerts.rules.yml"],
            "evaluation_interval": "30s",
            "tests": [t for slo in slos for t in alert_tests(slo)],
        }),
    }


def describe(slo: dict) -> str:
    budget_pct = num(slo["budget"] * 100)
    minutes = num(slo["budget"] * slo["days"] * 24 * 60)
    lines = [f"{slo['name']}: objective {num(slo['objective'])}%  ->  error budget {budget_pct}%"
             f" = {minutes} bad minutes per {slo['period']}"]
    for severity, _alert, windows in POLICY:
        conditions = " or ".join(f"> {num(factor * slo['budget'] * 100)}% ({long_w} and {short_w})"
                                 for long_w, short_w, factor in windows)
        lines.append(f"    {severity:<6} when the error ratio is {conditions}")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate Prometheus SLO rules from slos/slos.yaml")
    parser.add_argument("--check", action="store_true",
                        help="do not write anything; exit 1 if the generated files are out of date")
    args = parser.parse_args(argv)

    try:
        slos = load_spec(SPEC_FILE)
    except SpecError as exc:
        print(f"ERROR in slos/slos.yaml: {exc}", file=sys.stderr)
        return 1

    outputs = build(slos)
    if args.check:
        stale = [path for path, text in outputs.items()
                 if not path.exists() or path.read_text(encoding="utf-8") != text]
        for path in stale:
            print(f"OUT OF DATE: {path.relative_to(ROOT).as_posix()}", file=sys.stderr)
        if stale:
            print("Run:  python tools/slo_generator.py", file=sys.stderr)
            return 1
        print("Generated SLO files are up to date.")
        return 0

    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT).as_posix()}")
    print()
    for slo in slos:
        print(describe(slo))
    return 0


if __name__ == "__main__":
    sys.exit(main())
